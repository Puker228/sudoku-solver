#include <stddef.h>
#include <stdio.h>

int main(void) {
  int field[9][9] = {
      {6, 0, 0, 0, 7, 0, 0, 0, 2}, {0, 5, 8, 3, 6, 2, 4, 7, 0},
      {0, 0, 0, 9, 0, 8, 0, 0, 0}, {9, 6, 0, 0, 8, 0, 0, 1, 4},
      {0, 1, 2, 0, 0, 0, 8, 9, 0}, {8, 4, 0, 0, 9, 0, 0, 3, 5},
      {0, 0, 0, 8, 0, 7, 0, 0, 0}, {0, 3, 1, 4, 2, 6, 9, 5, 0},
      {4, 0, 0, 0, 1, 0, 0, 0, 7},
  };
  for (int i = 0; i < 9; i++) {
    for (int j = 0; j < 9; j++) {
      printf("%d ", field[i][j]);
      if (j == 2 || j == 5) {
        printf("| ");
      }
    }
    printf("\n");
    if (i == 2 || i == 5) {
      printf("------+-------+------\n");
    }
  }
  return 0;
}
